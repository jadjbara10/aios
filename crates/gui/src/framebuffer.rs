//! Direct linear framebuffer ops + tiny 8x16 bitmap font.
//!
//! The bootloader hands us a UEFI GOP framebuffer in
//! 'BootInfo.framebuffer': one contiguous run of 'height * stride'
//! pixels, each 'bpp/8' bytes. We assume 32 bpp xrgb8888 (the GOP's
//! preferred mode). No GPU yet — every pixel goes through a volatile
//! store through a raw pointer.
//!
//! Author: Jad Jbara <jad@aios.dev>
#![no_std]

pub type Color = u32;

/// Linear framebuffer descriptor. 'addr' is physical; the kernel
/// identity-maps the first 1 GiB in 'crates/bootloader::page_tables',
/// so we can write through it directly with no further paging.
pub struct Framebuffer {
    addr: usize,
    width: u32,
    height: u32,
    stride: u32,
    bpp: u8,
}

impl Framebuffer {
    pub fn new(addr: usize, width: u32, height: u32, stride: u32, bpp: u8) -> Self {
        assert!(bpp == 32, "AIOS GUI only supports 32bpp GOP mode");
        Self { addr, width, height, stride, bpp }
    }

    pub fn width(&self) -> u32 { self.width }
    pub fn height(&self) -> u32 { self.height }

    #[inline]
    fn in_bounds(&self, x: i32, y: i32) -> bool {
        x >= 0 && (x as u32) < self.width && y >= 0 && (y as u32) < self.height
    }

    /// Plot a single xrgb8888 pixel. Out-of-bounds writes are dropped.
    pub fn put_pixel(&self, x: i32, y: i32, color: Color) {
        if !self.in_bounds(x, y) { return; }
        let off = (y as usize) * (self.stride as usize) + (x as usize);
        let ptr = (self.addr as *mut u8).wrapping_add(off * 4) as *mut u32;
        // SAFETY: 'off' is in-bounds by 'in_bounds()'; the framebuffer is
        // a fixed memory range identity-mapped by the bootloader and we
        // hold the only alias (single-owner kernel handoff). The store is
        // volatile so the scan-out reads fresh pixels — this is the
        // canonical pixel write path.
        unsafe { core::ptr::write_volatile(ptr, color); }
    }

    /// Filled axis-aligned rectangle.
    pub fn fill_rect(&self, x: i32, y: i32, w: u32, h: u32, color: Color) {
        for ry in 0..h as i32 {
            for rx in 0..w as i32 {
                self.put_pixel(x + rx, y + ry, color);
            }
        }
    }

    /// Hollow 1px rectangle outline.
    pub fn draw_rect(&self, x: i32, y: i32, w: u32, h: u32, color: Color) {
        if w == 0 || h == 0 { return; }
        for rx in 0..w as i32 {
            self.put_pixel(x + rx, y, color);
            self.put_pixel(x + rx, y + h as i32 - 1, color);
        }
        for ry in 0..h as i32 {
            self.put_pixel(x, y + ry, color);
            self.put_pixel(x + w as i32 - 1, y + ry, color);
        }
    }

    /// Blit a source xrgb8888 surface (row-major, 'src_w * src_h'
    /// long) at (dx, dy). Out-of-bounds pixels are clipped;
    /// transparency is not yet supported — lands with AIOS-026.
    pub fn blit(&self, src: &[u32], src_w: u32, src_h: u32, dx: i32, dy: i32) {
        if src_w == 0 || src_h == 0 { return; }
        let expected = (src_w as usize) * (src_h as usize);
        if src.len() < expected { return; }
        for ry in 0..src_h as i32 {
            for rx in 0..src_w as i32 {
                let c = src[(ry as usize) * (src_w as usize) + (rx as usize)];
                self.put_pixel(dx + rx, dy + ry, c);
            }
        }
    }

    /// Draw an 8x16 glyph at (x, y) in the foreground color. Unknown
    /// characters render as a blank 8x16 cell.
    pub fn draw_glyph(&self, ch: u8, x: i32, y: i32, fg: Color) {
        let glyph = font_lookup(ch);
        for row in 0..16usize {
            let bits = glyph[row];
            for col in 0..8u32 {
                if (bits >> (7 - col)) & 1 == 1 {
                    self.put_pixel(x + col as i32, y + row as i32, fg);
                }
            }
        }
    }
}

/// Draw a left-to-right text string at (x, y) in the foreground color.
/// Each glyph is 8 px wide; lines advance by 16 px. Out-of-frame
/// glyphs are clipped by 'put_pixel'.
pub fn draw_text(fb: &Framebuffer, x: i32, y: i32, text: &str, fg: Color) {
    let mut cx = x;
    for b in text.bytes() {
        fb.draw_glyph(b, cx, y, fg);
        cx += 8;
    }
}

